#!/bin/sh
# Regenerates vk_canonical_shaders.h from the GLSL beside it.
#
# The Vulkan path embeds its SPIR-V as a C array: the game links no shader compiler, and a missing
# or mismatched shader file at run time would be a black screen instead of a build error. Run this
# after editing vk_canonical.vert or vk_canonical.frag, then rebuild.
#
# Requires glslangValidator (Debian: glslang-tools).
set -e
cd "$(dirname "$0")"

GLSLANG=${GLSLANG:-glslangValidator}
OUT=vk_canonical_shaders.h
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

"$GLSLANG" -V --target-env vulkan1.1 vk_canonical.vert -o "$TMP/vert.spv" > /dev/null
"$GLSLANG" -V --target-env vulkan1.1 vk_canonical.frag -o "$TMP/frag.spv" > /dev/null

emit() {
	name=$1
	file=$2
	echo "static const uint32_t $name[] = {"
	od -An -v -tu4 "$file" | awk '{
		line = ""
		for (i = 1; i <= NF; ++i) line = line sprintf("0x%08xu,", $i)
		print "    " line
	}'
	echo "};"
}

{
	echo "// Generated by regen_vk_shaders.sh from vk_canonical.vert and vk_canonical.frag."
	echo "// Do not edit by hand: edit the GLSL and run the script."
	echo "#ifndef VK_CANONICAL_SHADERS_H"
	echo "#define VK_CANONICAL_SHADERS_H"
	echo
	echo "#include <cstdint>"
	echo
	emit s_canonicalVertexSPIRV "$TMP/vert.spv"
	echo
	emit s_canonicalFragmentSPIRV "$TMP/frag.spv"
	echo
	echo "#endif // VK_CANONICAL_SHADERS_H"
} > "$OUT"

echo "wrote $OUT"
